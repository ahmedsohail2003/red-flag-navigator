// The home monitoring kit's catalogue: every active test, every device signal, the
// post-diagnosis action triggers and the "what actually detects anything" table.
// Pure data, no DOM or storage: runs in the browser and in Node.
//
// Every clinical number here comes from tonight's fact-checked research notes
// ("Home monitoring beyond gyros", their Verification sections winning), the earlier
// "Phone and wearable ALS signals" notes or docs/WEARABLES.md, and carries the URL it
// came from. "Computed by us" (computedByUs: true) marks arithmetic the researchers did
// on a published figure. Nothing in the kit has been validated for finding undiagnosed
// ALS: almost every cohort below was already diagnosed (the exceptions look back at
// registry or GP records, or studied people already referred with suspected ALS).
// Shape: plans/home-monitoring-contracts.md.
//
// Words used in the fields:
//   mdc        minimal detectable change: the smallest change bigger than test-to-test
//              noise. unit is the entry's own unit (an absolute change), or
//              '% of baseline' (a share of the person's own baseline; see mdcFor).
//   feeds      'engine-candidate': may become a weekly home test in the engine's
//              decline rule (one region, with an MDC). 'clinician-prompt': never scored
//              directly; a result past a threshold prompts the clinician to ask, examine
//              or test. 'context': shown beside the score, never counts toward it.
//   verdict    'detects': could help flag possible ALS before diagnosis (always through a
//              clinician). 'monitors': useful after diagnosis. 'context': worth showing,
//              not evidence of ALS. 'no use'.
//   grade      the ALS evidence: strong, moderate, weak, not studied (closest evidence
//              given); 'contradicted' (added to the contract) where the notes say the
//              evidence goes against the signal changing.
//   implementation 'working': a standard method (a stopwatch, a count, a checklist);
//              'experimental': our own microphone or typing timing tool, not validated;
//              'manual': a reading from another device or form, typed in.
//   weekly     how a week's values become one (series.toWeekly). Every signal has its
//              own. On a test (added), only the questionnaires: their week is the highest
//              answer, so a red-flag answer is never averaged away by a second one.
//   redFlag    (added) an answer that needs the doctor soon, before or after diagnosis:
//              on a question, a Yes; on a test, a total of atLeast or more. urgency
//              'today' (the same day) or 'now'.
//   nearFall   (added) marks the falls option that means a near-fall: it scores 0 (the
//              score counts falls), and the result is saved as a near-fall.

export const PCT_OF_BASELINE = '% of baseline';

// The MDC in the entry's own units, for series.assessDecline. A '% of baseline' MDC
// becomes that share of the person's baseline. null when there is none.
export function mdcFor(entry, baselineValue) {
  const m = entry?.mdc;
  if (!m || !Number.isFinite(m.value) || !(m.value > 0)) return null;
  if (m.unit !== PCT_OF_BASELINE) return m.value;
  if (!Number.isFinite(baselineValue) || baselineValue === 0) return null;
  return (Math.abs(baselineValue) * m.value) / 100;
}

