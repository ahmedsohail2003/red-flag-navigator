"""Write app/js/wearables.js from docs/wearables.json (the phone and wearable research),
so the Monitoring view shows the researched signals without anyone retyping them.
Re-run after the research file changes:  python -I analysis/make_wearables_js.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = ROOT / "docs" / "wearables.json"
data = json.loads(src.read_text(encoding="utf-8"))
signals = data["signals"] if isinstance(data, dict) and "signals" in data else data
if not isinstance(signals, list) or not signals:
    raise SystemExit("docs/wearables.json has no signals")

required = ["signal", "region", "evidence_grade", "sources"]
for i, s in enumerate(signals):
    missing = [k for k in required if k not in s]
    if missing:
        raise SystemExit(f"signal {i} ({s.get('signal')}) is missing {missing}")

out = ROOT / "app" / "js" / "wearables.js"
out.write_text(
    "// Generated by analysis/make_wearables_js.py from docs/wearables.json\n"
    "// (phone and wearable research, with sources). Do not edit by hand.\n"
    f"export const WEARABLES = {json.dumps(signals, ensure_ascii=False, indent=1)};\n",
    encoding="utf-8",
)
grades = {}
for s in signals:
    grades[s.get("evidence_grade")] = grades.get(s.get("evidence_grade"), 0) + 1
print(f"wrote {out} with {len(signals)} signals; evidence grades: {grades}")
print("demo picks:", [s["signal"] for s in signals if s.get("demo")])
