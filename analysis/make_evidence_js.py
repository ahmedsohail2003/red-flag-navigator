"""Write app/js/evidence.js from analysis/results.json, so the pages show the analysis
numbers without anyone retyping them. Re-run after re-running the analyses."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
r = json.loads((ROOT / "analysis" / "results.json").read_text(encoding="utf-8"))
g = r["gait"]
ttr = g["test_retest_controls"]["features"]

LABELS = {
    "mean_stride_s": ("Mean stride time", "s"),
    "cv_pct": ("Stride-time variability (CV)", "%"),
    "swing_pct": ("Swing phase (share of the stride)", "%"),
}

def pair(d):
    return {"auc": round(d["auc"], 2), "ci": [round(d["auc_ci95"][0], 2), round(d["auc_ci95"][1], 2)], "p": d["p_two_sided"], "nAls": d["n_als"], "nOther": d["n_other"]}

features = []
for key, f in g["features"].items():
    label, unit = LABELS[key]
    gs = f["group_stats"]
    features.append({
        "key": key, "label": label, "unit": unit, "direction": f["auc_orientation"],
        "medians": {k: round(v["median"], 2) for k, v in gs.items()},
        "alsVsControl": pair(f["als_vs_control"]),
        "alsVsParkinsons": pair(f["als_vs_parkinsons"]),
        "alsVsHuntingtons": pair(f["als_vs_huntingtons"]),
        "mdc95": round(ttr[key]["mdc95"], 3) if key in ttr else None,
    })

def delay(block, sites):
    o = block["overall"]
    return {
        "source": block["source"],
        "n": o["n"], "medianMonths": o["median_months"], "iqrMonths": o["iqr_months"], "pctOver12": o.get("pct_over_12_months"),
        "bySite": {s: {"n": block["by_onset_site"][s]["n"], "medianMonths": block["by_onset_site"][s]["median_months"], "iqrMonths": block["by_onset_site"][s]["iqr_months"]} for s in sites if s in block["by_onset_site"]},
    }

d = r.get("delay") or {}
evidence = {
    "gait": {
        "source": "PhysioNet Gait in Neurodegenerative Disease Database 1.0.0 (one 5-minute walk per person, foot force sensors)",
        "n": g["n"],
        "features": features,
        "bestFeature": g["best_feature"]["feature"],
        "bestFeatureNote": "Picked as the best of three after looking at the data, so its AUC is optimistic.",
        "mdcMethod": "Each control's walk split into two halves; MDC95 = 1.96 x sqrt(2) x within-person SD. Halves of one walk understate week-to-week noise.",
    },
    "delay": {
        "alsFocus": delay(d["als_focus"], ["bulbar", "upper_limb", "lower_limb"]) if d.get("als_focus") else None,
        "seattle": delay(d["seattle"], ["bulbar", "limb"]) if d.get("seattle") else None,
    } if d else None,
    "limits": [
        "Small groups (13 ALS, 16 controls); p-values not corrected for testing several features.",
        "Groups not matched: ALS median age 62 vs 35 in controls. With only controls aged 36 or over (8 people), the AUCs held.",
        "The ALS patients were already diagnosed, not in the pre-diagnosis window the tool targets.",
        "The ALS rows in the dataset's subject file are labelled and rounded differently, so they may have been recorded separately from the other groups; that could inflate the separation (not verified).",
        "Lab force sensors, not a phone. Parkinson's and Huntington's are not the usual ALS look-alikes; neuropathy, myelopathy and myopathy were not tested.",
        "Diagnostic delays are recalled by diagnosed patients; the Seattle cohort was enrolled in 1987-88.",
    ],
}

out = ROOT / "app" / "js" / "evidence.js"
out.write_text(
    "// Generated by analysis/make_evidence_js.py from analysis/results.json. Do not edit by hand.\n"
    "export const EVIDENCE = " + json.dumps(evidence, indent=2) + ";\n",
    encoding="utf-8",
)
print("wrote", out)
for f in features:
    print(f["key"], f["medians"], f["alsVsControl"], "mdc", f["mdc95"])
print(json.dumps(evidence["delay"], indent=1)[:900])
